const themeToggle = document.getElementById("us-theme-toggle");
function syncIcon() {
  const current = document.documentElement.getAttribute("data-theme");
  const icon = themeToggle.querySelector("i");
  if (!icon) return;
  icon.className = current === "dark" ? "bi bi-sun" : "bi bi-moon-stars";
}
syncIcon();
themeToggle.addEventListener("click", () => {
  const next = document.documentElement.getAttribute("data-theme") === "dark" ? "light" : "dark";
  document.documentElement.setAttribute("data-theme", next);
  localStorage.setItem("theme", next);
  syncIcon();
});

let activeId = stories.length > 0 ? stories[0].id : null;

function renderList() {
  const list = document.getElementById("us-story-list");
  if (!stories.length) {
    list.innerHTML = '<div class="us-no-stories">Belum ada cerita.</div>';
    return;
  }
  list.innerHTML = stories.map(s => `
    <div class="us-story-item${s.id === activeId ? " active" : ""}" data-id="${s.id}">
      <span class="us-item-date">${s.date}</span>
      <span class="us-item-title">${s.title}</span>
      <span class="us-item-preview">${s.preview}</span>
    </div>
  `).join("");
  list.querySelectorAll(".us-story-item").forEach(el => {
    el.addEventListener("click", () => {
      const id = parseInt(el.dataset.id, 10);
      openStory(id);
    });
  });
}

function renderContent() {
  const body = document.getElementById("us-story-body");
  if (!activeId) {
    body.innerHTML = `
      <div class="us-empty">
        <span class="us-empty-icon">✦</span>
        <span class="us-empty-text">Pilih cerita untuk dibaca.</span>
      </div>`;
    return;
  }
  const story = stories.find(s => s.id === activeId);
  if (!story) return;
  body.innerHTML = `
    <div class="story-meta">
      <span class="story-date">${story.date}</span>
      <h1 class="story-title">${story.title}</h1>
    </div>
    <div class="story-body">${story.content}</div>
  `;
}

function openStory(id) {
  activeId = id;
  renderList();
  renderContent();
  const isMobile = window.innerWidth <= 768;
  if (isMobile) {
    const content = document.getElementById("us-content");
    setTimeout(() => {
      content.scrollIntoView({ behavior: "smooth", block: "start" });
    }, 80);
  } else {
    const content = document.getElementById("us-content");
    content.scrollTo({ top: 0, behavior: "smooth" });
  }
}

renderList();
renderContent();
